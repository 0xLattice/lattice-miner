#[test]
fn targets_and_minimum_work_parse_as_the_swift_core_did() {
    for (input, target, work) in PARSES {
        assert_eq!(
            parse_target(input).map(hex::encode).as_deref(),
            *target,
            "target {input:?}"
        );
        assert_eq!(
            parse_minimum_work(input).map(hex::encode).as_deref(),
            *work,
            "work {input:?}"
        );
    }
}

