#[test]
fn nonce_ranges_are_shared_out_as_the_swift_core_did() {
    assert_eq!(RANGES.len(), 72);
    for (total, workers, offset, expected) in RANGES {
        let actual: Vec<_> = allocate_ranges(*total, *workers, *offset)
            .into_iter()
            .map(|r| (r.start_nonce, r.count))
            .collect();
        assert_eq!(actual, *expected, "{total} across {workers} from {offset}");
    }
}
